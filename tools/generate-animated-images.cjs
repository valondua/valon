const hash = bytes => createHash('sha256').update(bytes).digest('hex');
class IntentionalSkip extends Error {}
const metadata = value => ({ width: value.width, height: value.pageHeight, frames: value.pages, delay: value.delay, loop: value.loop });
function assertMetadata(actual, expected) {
  for (const key of ['width', 'height', 'frames', 'delay', 'loop']) {
    if (JSON.stringify(actual[key]) !== JSON.stringify(expected[key])) throw new Error(`Animation ${key} changed`);
  }
}
async function verifyOriginal(bytes, spec) {
  if (hash(bytes) !== spec.sourceSha256) throw new Error('Original source SHA-256 changed; review required');
  if (bytes.length !== spec.sourceBytes) throw new Error('Original source byte count changed');
  const result = await sharp(bytes, { animated: true }).metadata();
  if (result.format !== 'gif') throw new Error('Pinned source is not a GIF');
  assertMetadata(metadata(result), spec);
  return result;
}
function comparePixels(original, output, spec) {
  const stride = spec.width * spec.height * 4;
  if (original.length !== output.length || original.length !== stride * spec.frames) throw new Error('Decoded frame dimensions changed');
  let totalSquare = 0, totalCount = 0, alphaChanged = 0, worstFramePsnr = Infinity;
  for (let frame = 0; frame < spec.frames; frame++) {
    let square = 0, count = 0;
    for (let i = frame * stride; i < (frame + 1) * stride; i += 4) {
      if (original[i + 3] !== output[i + 3]) alphaChanged++;
      if (original[i + 3] === 0 && output[i + 3] === 0) continue;
      for (let c = 0; c < 3; c++) { const delta = original[i + c] - output[i + c]; square += delta * delta; count++; }
    }
    const psnr = square ? 10 * Math.log10(255 * 255 * count / square) : Infinity;
    worstFramePsnr = Math.min(worstFramePsnr, psnr);
    totalSquare += square; totalCount += count;
  }
  const psnr = totalSquare ? 10 * Math.log10(255 * 255 * totalCount / totalSquare) : Infinity;
  return { allFramesCompared: spec.frames, alphaChangedPixels: alphaChanged, psnr, worstFramePsnr };
}
async function generate({ reportDir, sourceDir = path.join(reportDir, 'sources'), outputDir = path.join(ROOT, 'assets'), sources = SOURCES }) {
  sharp.concurrency(1);
  sharp.cache({ memory: 32, files: 5, items: 20 });
  await fs.mkdir(reportDir, { recursive: true });
  await fs.mkdir(sourceDir, { recursive: true });
  await fs.mkdir(outputDir, { recursive: true });
  const report = { created: new Date().toISOString(), sharp: sharp.versions, options: OPTIONS, concurrency: 1, sources: [] };
  const manifest = {};
  for (const spec of sources) {
    const row = { ...spec, status: 'skipped' };
    try {
      const sourcePath = path.join(sourceDir, spec.id + '.gif');
      let input;
      try { input = await fs.readFile(sourcePath); } catch (error) {
        if (error.code !== 'ENOENT') throw error;
        const response = await fetch(spec.url, { signal: AbortSignal.timeout(60000) });
        if (!response.ok) throw new Error(`Original download failed: HTTP ${response.status}`);
        input = Buffer.from(await response.arrayBuffer());
        await verifyOriginal(input, spec);
        await fs.writeFile(sourcePath, input);
      }
      await verifyOriginal(input, spec);
      if (spec.frames < 2 || spec.delay.some(delay => delay <= 0)) {
        throw new IntentionalSkip('Original has zero-delay frames; preserve GIF because browser format-specific delay clamping is not proven equivalent');
      }
      const file = `valon-animation-${spec.id}.webp`;
      const outputPath = path.join(reportDir, file);
      await sharp(input, { animated: true }).webp({ ...OPTIONS, delay: spec.delay, loop: spec.loop }).toFile(outputPath);
      const output = await fs.readFile(outputPath);
      const outputMeta = await sharp(output, { animated: true }).metadata();
      if (outputMeta.format !== 'webp') throw new Error('Unexpected output format');
      assertMetadata(metadata(outputMeta), spec);
      const originalPixels = await sharp(input, { animated: true }).ensureAlpha().raw().toBuffer();
      const outputPixels = await sharp(output, { animated: true }).ensureAlpha().raw().toBuffer();
      row.fidelity = comparePixels(originalPixels, outputPixels, spec);
      row.outputBytes = output.length;
      row.savedBytes = input.length - output.length;
      row.savedPercent = 100 * (1 - output.length / input.length);
      row.outputSha256 = hash(output);
      row.file = file;
      if (row.fidelity.alphaChangedPixels) throw new IntentionalSkip('Decoded alpha changed; preserve the original GIF');
      if (row.fidelity.psnr < 32 || row.fidelity.worstFramePsnr < 28) throw new IntentionalSkip('Conservative all-frame RGB fidelity threshold failed; preserve the original GIF');
      if (row.savedPercent < 15) throw new IntentionalSkip('Less than 15% transfer saving');
      // Store visual review samples outside the repository; all frames were checked above.
      for (const frame of [0, Math.floor(spec.frames / 2), spec.frames - 1]) {
        await sharp(input, { page: frame, pages: 1 }).png().toFile(path.join(reportDir, `${spec.id}-original-${frame}.png`));
        await sharp(output, { page: frame, pages: 1 }).png().toFile(path.join(reportDir, `${spec.id}-webp-${frame}.png`));
      }
      await fs.copyFile(outputPath, path.join(outputDir, file));
      manifest[spec.url] = { file, width: spec.width, height: spec.height, frames: spec.frames, delay: spec.delay, loop: spec.loop,
        source_sha256: spec.sourceSha256, source_bytes: spec.sourceBytes, bytes: output.length, sha256: row.outputSha256 };
      row.status = 'accepted';
    } catch (error) {
      row.status = error instanceof IntentionalSkip ? 'skipped' : 'failed';
      row.reason = error.message;
    }
    report.sources.push(row);
    await fs.writeFile(path.join(reportDir, 'generation-report.json'), JSON.stringify(report, null, 2) + '\n');
    console.log(JSON.stringify({ id: row.id, status: row.status, savedPercent: row.savedPercent, reason: row.reason }));
  }
  const failures = report.sources.filter(source => source.status === 'failed');
  if (failures.length) {
    throw new Error(`${failures.length} unexpected source or conversion failure(s); prior animation manifest preserved. See ${path.join(reportDir, 'generation-report.json')}`);
  }
  const temporaryManifest = path.join(outputDir, 'optimized-animations.json.tmp');
  await fs.writeFile(temporaryManifest, JSON.stringify(manifest, null, 2) + '\n');
  await fs.rename(temporaryManifest, path.join(outputDir, 'optimized-animations.json'));
  return report;
}
